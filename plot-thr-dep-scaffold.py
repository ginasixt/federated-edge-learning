def trimmed_decimal_formatter(max_decimals: int) -> FuncFormatter:
    def _format(value: float, _position: object) -> str:
        if not np.isfinite(value):
            return ""
        text = f"{value:.{max_decimals}f}".rstrip("0").rstrip(".")
        return "0" if text in {"", "-0"} else text

    return FuncFormatter(_format)


def padded_limits(
    values: Iterable[float],
    minimum_span: float,
    include_value: Optional[float] = None,
    padding_fraction: float = 0.12,
    hard_bounds: Optional[Tuple[float, float]] = None,
) -> Tuple[float, float]:
    array = np.asarray(list(values), dtype=float)
    array = array[np.isfinite(array)]
    if array.size == 0:
        return (0.0, 1.0)

    low = float(np.min(array))
    high = float(np.max(array))
    if include_value is not None:
        low = min(low, include_value)
        high = max(high, include_value)

    center = (low + high) / 2.0
    span = max(high - low, minimum_span)
    low = center - span / 2.0
    high = center + span / 2.0
    padding = span * padding_fraction
    low -= padding
    high += padding

    if hard_bounds is not None:
        low = max(hard_bounds[0], low)
        high = min(hard_bounds[1], high)

    if np.isclose(low, high):
        high = low + minimum_span
    return low, high


def scatter_individual_runs(
    ax: plt.Axes,
    raw: pd.DataFrame,
    clients: Sequence[int],
    metric: str,
    marker: str = "o",
    jitter_offset: float = 0.0,
    facecolor: str = INDIVIDUAL_RUN_GRAY,
    alpha: float = 0.65,
) -> List[float]:
    all_values: List[float] = []

    for clients_value in clients:
        values = (
            raw[raw["scaling_point"] == clients_value]
            .sort_values("run")[metric]
            .to_numpy(dtype=float)
        )
        x_center = float(np.log2(clients_value))
        jitter = deterministic_jitter(len(values)) + jitter_offset

        ax.scatter(
            x_center + jitter,
            values,
            s=INDIVIDUAL_POINT_SIZE,
            marker=marker,
            facecolor=facecolor,
            edgecolor="white",
            linewidth=0.35,
            alpha=alpha,
            zorder=2,
        )
        all_values.extend(values.tolist())

    return all_values


def plot_mean_line(
    ax: plt.Axes,
    aggregate: pd.DataFrame,
    metric: str,
    color: str,
    marker: str = "o",
    linestyle: str = "-",
    markerfacecolor: Optional[str] = None,
) -> None:
    x = client_positions(aggregate["scaling_point"].to_numpy(dtype=int))
    means = aggregate[f"{metric}_mean"].to_numpy(dtype=float)
    facecolor = color if markerfacecolor is None else markerfacecolor

    ax.plot(
        x,
        means,
        color=color,
        linewidth=LINE_WIDTH,
        linestyle=linestyle,
        alpha=0.97,
        marker=marker,
        markersize=MARKER_SIZE,
        markerfacecolor=facecolor,
        markeredgecolor="white" if facecolor != "white" else color,
        markeredgewidth=MARKER_EDGE_WIDTH,
        zorder=3,
    )


