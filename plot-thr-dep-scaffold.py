def finite_float(value: Any) -> float:
    number = float(value)
    if not np.isfinite(number):
        raise ValueError(f"Non-finite numeric value: {value!r}")
    return number


def flatten_threshold_json(path: Path) -> List[Dict[str, Any]]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"Expected JSON object in {path}")

    strategy = str(payload.get("strategy", DEFAULT_STRATEGY))
    scaling_point = int(payload["scaling_point"])
    run = int(payload["run"])

    rows: List[Dict[str, Any]] = []
    regime_map = (
        ("mcc_optimal", "mcc_optimal"),
        ("minimum_recall", "minimum_recall"),
    )

    for json_key, regime in regime_map:
        section = payload.get(json_key)
        if not isinstance(section, dict):
            raise KeyError(f"Missing '{json_key}' object in {path}")

        validation = section.get("validation_selection")
        test = section.get("test_evaluation")
        if not isinstance(validation, dict) or not isinstance(test, dict):
            raise KeyError(
                f"Missing validation_selection or test_evaluation in "
                f"{path}: {json_key}"
            )

        row: Dict[str, Any] = {
            "strategy": strategy,
            "scaling_point": scaling_point,
            "run": run,
            "threshold_regime": regime,
            "selected_threshold": validation.get("threshold"),
            "validation_mcc": validation.get("mcc"),
            "validation_recall": validation.get("recall"),
            "validation_specificity": validation.get("specificity"),
            "test_mcc": test.get("mcc"),
            "test_recall": test.get("recall"),
            "test_specificity": test.get("specificity"),
            "test_precision": test.get("precision"),
            "test_f1": test.get("f1"),
            "test_balanced_accuracy": test.get("balanced_accuracy"),
            "test_false_positive_rate": test.get("false_positive_rate"),
            "test_false_positives_per_1000_negatives": test.get(
                "false_positives_per_1000_negatives"
            ),
            "source_json": str(path),
        }

        if regime == "minimum_recall":
            row["minimum_validation_recall_requirement"] = validation.get(
                "minimum_recall"
            )

        rows.append(row)

    return rows


def read_json_tree(root: Path) -> pd.DataFrame:
    files = sorted(root.glob("splits_iid_*_clients/run_*/threshold_results.json"))
    if not files:
        files = sorted(root.rglob("threshold_results.json"))
    if not files:
        raise FileNotFoundError(
            f"No threshold_results.json files found under:\n  {root}"
        )

    rows: List[Dict[str, Any]] = []
    for path in files:
        rows.extend(flatten_threshold_json(path))
    return pd.DataFrame.from_records(rows)


def read_input(path: Path) -> pd.DataFrame:
    if path.is_file():
        if path.suffix.lower() != ".csv":
            raise ValueError(
                "The input file must be all_threshold_results.csv. "
                "Alternatively pass the directory containing threshold_results.json."
            )
        return pd.read_csv(path)

    if path.is_dir():
        csv_path = path / "all_threshold_results.csv"
        if csv_path.is_file():
            return pd.read_csv(csv_path)
        return read_json_tree(path)

    # Helpful automatic fallback when the default CSV has not been written but
    # its parent contains the per-run threshold_results.json files.
    if path.name == "all_threshold_results.csv" and path.parent.is_dir():
        return read_json_tree(path.parent)

    raise FileNotFoundError(
        f"Threshold-dependent input not found:\n  {path}\n\n"
        "The threshold-independent final_test_set_eval/test_summary.json files "
        "cannot be used for validation-based threshold plots."
    )


def normalize_and_validate(
    data: pd.DataFrame,
    strategy: str,
    expected_runs: int,
    expected_scaling_points: int,
) -> pd.DataFrame:
    missing = REQUIRED_COLUMNS - set(data.columns)
    if missing:
        raise ValueError(
            "Input is missing required threshold-dependent columns:\n  "
            + "\n  ".join(sorted(missing))
        )

    frame = data.copy()
    frame["strategy"] = frame["strategy"].astype(str)
    frame["threshold_regime"] = (
        frame["threshold_regime"]
        .astype(str)
        .str.strip()
        .str.lower()
        .replace(
            {
                "maximum_validation_mcc": "mcc_optimal",
                "maximum_mcc": "mcc_optimal",
                "recall_constrained": "minimum_recall",
                "fixed_recall": "minimum_recall",
            }
        )
    )

    numeric_columns = [
        "scaling_point",
        "run",
        "selected_threshold",
        "test_mcc",
        "test_recall",
        "test_specificity",
    ]
    optional_numeric = [
        "minimum_validation_recall_requirement",
        "validation_mcc",
        "validation_recall",
        "validation_specificity",
        "test_precision",
        "test_f1",
        "test_balanced_accuracy",
        "test_false_positive_rate",
        "test_false_positives_per_1000_negatives",
    ]

    for column in numeric_columns + [
        column for column in optional_numeric if column in frame.columns
    ]:
        frame[column] = pd.to_numeric(frame[column], errors="coerce")

    if frame[numeric_columns].isna().any().any():
        invalid = frame[frame[numeric_columns].isna().any(axis=1)]
        raise ValueError(
            "Invalid required numeric threshold results:\n"
            + invalid.head(10).to_string(index=False)
        )

    frame["scaling_point"] = frame["scaling_point"].astype(int)
    frame["run"] = frame["run"].astype(int)
    frame = frame[
        (frame["strategy"] == strategy)
        & frame["threshold_regime"].isin({"mcc_optimal", "minimum_recall"})
    ].copy()

    if frame.empty:
        raise ValueError(
            f"No MCC-optimal or minimum-recall rows found for strategy '{strategy}'."
        )

    duplicate_key = ["strategy", "scaling_point", "run", "threshold_regime"]
    duplicates = frame.duplicated(duplicate_key, keep=False)
    if duplicates.any():
        raise ValueError(
            "Duplicate run/regime rows found:\n"
            + frame.loc[duplicates, duplicate_key]
            .sort_values(duplicate_key)
            .to_string(index=False)
        )

    for regime in ("mcc_optimal", "minimum_recall"):
        subset = frame[frame["threshold_regime"] == regime]
        n_points = subset["scaling_point"].nunique()
        if n_points != expected_scaling_points:
            raise ValueError(
                f"{regime}: expected {expected_scaling_points} scaling points, "
                f"found {n_points}."
            )

        run_counts = subset.groupby("scaling_point")["run"].nunique()
        incorrect = run_counts[run_counts != expected_runs]
        if not incorrect.empty:
            details = ", ".join(
                f"{int(clients)} clients: n={int(count)}"
                for clients, count in incorrect.items()
            )
            raise ValueError(
                f"{regime}: expected {expected_runs} runs at every point; {details}."
            )

    observed = sorted(frame["scaling_point"].unique().tolist())
    if tuple(observed) != SCALING_POINTS:
        print(
            "Warning: observed scaling points differ from the default sequence:\n"
            f"  {observed}"
        )

    return frame.sort_values(
        ["threshold_regime", "scaling_point", "run"]
    ).reset_index(drop=True)


