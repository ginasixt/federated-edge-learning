def aggregate_results(raw: pd.DataFrame) -> pd.DataFrame:
    metrics = [
        "selected_threshold",
        "test_mcc",
        "test_recall",
        "test_specificity",
    ]
    optional = [
        "validation_mcc",
        "validation_recall",
        "validation_specificity",
        "test_precision",
        "test_f1",
        "test_balanced_accuracy",
        "test_false_positive_rate",
        "test_false_positives_per_1000_negatives",
    ]
    metrics.extend(column for column in optional if column in raw.columns)

    records: List[Dict[str, Any]] = []
    grouped = raw.groupby(
        ["strategy", "threshold_regime", "scaling_point"],
        sort=True,
    )

    for (strategy, regime, clients), group in grouped:
        record: Dict[str, Any] = {
            "strategy": strategy,
            "threshold_regime": regime,
            "scaling_point": int(clients),
            "n_runs": int(group["run"].nunique()),
        }

        for metric in metrics:
            values = pd.to_numeric(group[metric], errors="coerce").dropna()
            if values.empty:
                continue
            record[f"{metric}_mean"] = float(values.mean())
            record[f"{metric}_std"] = (
                float(values.std(ddof=1)) if len(values) > 1 else 0.0
            )
            record[f"{metric}_min"] = float(values.min())
            record[f"{metric}_max"] = float(values.max())

        records.append(record)

    return pd.DataFrame.from_records(records).sort_values(
        ["threshold_regime", "scaling_point"]
    )


def get_minimum_recall_requirement(raw: pd.DataFrame) -> float:
    if "minimum_validation_recall_requirement" not in raw.columns:
        raise ValueError(
            "The minimum-recall rows do not contain "
            "'minimum_validation_recall_requirement'."
        )

    values = (
        pd.to_numeric(
            raw.loc[
                raw["threshold_regime"] == "minimum_recall",
                "minimum_validation_recall_requirement",
            ],
            errors="coerce",
        )
        .dropna()
        .unique()
    )

    if len(values) != 1:
        raise ValueError(
            "Expected one prespecified validation-recall requirement, found: "
            + ", ".join(f"{value:.6g}" for value in sorted(values))
        )
    requirement = float(values[0])
    if not (0.0 < requirement <= 1.0):
        raise ValueError(f"Invalid minimum recall requirement: {requirement}")
    return requirement


