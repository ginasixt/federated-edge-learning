def main() -> None:
    args = parse_args()
    font_name = available_font(args.font)
    configure_matplotlib(font_name)

    print("=" * 82)
    print("APA-STYLE THRESHOLD-DEPENDENT SCAFFOLD FIGURES")
    print(f"Input     : {args.input}")
    print(f"Output    : {args.output_dir}")
    print(f"Strategy  : {args.strategy}")
    print(f"Font      : {font_name}")
    print(f"Formats   : {', '.join(args.formats)}")
    print("=" * 82)

    raw = read_input(args.input)
    raw = normalize_and_validate(
        raw,
        strategy=args.strategy,
        expected_runs=args.expected_runs,
        expected_scaling_points=args.expected_scaling_points,
    )
    aggregate = aggregate_results(raw)
    minimum_recall = get_minimum_recall_requirement(raw)

    args.output_dir.mkdir(parents=True, exist_ok=True)

    raw_path = args.output_dir / "threshold_dependent_run_results.csv"
    aggregate_path = args.output_dir / "threshold_dependent_aggregate.csv"
