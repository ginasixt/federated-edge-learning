"""
APA-style threshold-dependent SCAFFOLD scalability figures.

This script PLOTS threshold-dependent results that were already generated by
the validation-based threshold evaluation pipeline. It does not select a model,
round, or threshold and does not optimize anything on the test set.

Expected default input
----------------------
result/splits_iid_scaling/final_threshold_analysis/SCAFFOLD/
    all_threshold_results.csv

Alternatively, pass the analysis directory itself. The script then reads all:

    splits_iid_<N>_clients/run_<r>/threshold_results.json

Important
---------
The threshold-independent files under:

    result/splits_iid_scaling/final_test_set_eval/SCAFFOLD/

such as test_metrics.json and test_summary.json are not sufficient for these
plots because they do not contain the two validation-selected operating points.

Generated figures
-----------------
Figure 1: MCC-optimal operating point
    A. Validation-selected decision threshold
    B. Test MCC
    C. Test recall and specificity

Figure 2: Fixed minimum-recall operating point
    A. Validation-selected decision threshold
    B. Test recall and specificity with the prespecified validation-recall reference

Design
------
* same UHH-based colors, font sizes, axes, markers, and spacing as the
  threshold-independent thesis figures
* no decorative titles inside the figures
* bold panel labels A-C only
* small gray points for individual runs
* colored circles and lines for means across five repeated runs
* one shared neutral legend below each figure
* base-2 logarithmic client axis
* PDF and high-resolution PNG output
* suggested APA captions written to a text file

Example
-------
python plot-thr-dependent-scaffold.py

python plot-thr-dependent-scaffold.py \
    --input result/splits_iid_scaling/final_threshold_analysis/SCAFFOLD

python plot-thr-dependent-scaffold.py \
    --input result/splits_iid_scaling/final_threshold_analysis/SCAFFOLD/all_threshold_results.csv \
    --output-dir result/splits_iid_scaling/final_threshold_analysis/SCAFFOLD/apa_figures
"""

